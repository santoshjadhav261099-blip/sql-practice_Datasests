create database My_Imp;
use My_Imp;

-- employees Table
CREATE TABLE employees (
    id INT PRIMARY KEY,
    name VARCHAR(100),
    gender VARCHAR(10),
    salary INT,
    department_id INT,
    manager_id INT,
    hire_date DATE
);

--departments
CREATE TABLE departments (
    department_id INT PRIMARY KEY,
    department_name VARCHAR(100),
    creation_date DATE
);

-- salary_history
CREATE TABLE salary_history (
    id INT PRIMARY KEY,
    employee_id INT,
    old_salary INT,
    new_salary INT,
    change_date DATE
);

-- promotions
CREATE TABLE promotions (
    promotion_id INT PRIMARY KEY,
    employee_id INT,
    promotion_date DATE
);


--projects
CREATE TABLE projects (
    project_id INT PRIMARY KEY,
    project_name VARCHAR(100),
    department_id INT,
    start_date DATE,
    end_date DATE,
    budget INT
);

--project_assignments

CREATE TABLE project_assignments (
    assignment_id INT PRIMARY KEY,
    employee_id INT,
    project_id INT,
    start_date DATE,
    end_date DATE
);

-- customers
CREATE TABLE customers (
    customer_id INT PRIMARY KEY,
    name VARCHAR(100),
    country VARCHAR(50),
    signup_date DATE
);

-- products
CREATE TABLE products (
    product_id INT PRIMARY KEY,
    product_name VARCHAR(100),
    category_id INT,
    price INT
);

--sales
CREATE TABLE sales (
    sale_id INT PRIMARY KEY,
    customer_id INT,
    product_id INT,
    amount INT,
    quantity INT,
    sale_date DATE
);

-- orders

CREATE TABLE orders (
    order_id INT PRIMARY KEY,
    customer_id INT,
    order_date DATE,
    shipping_method VARCHAR(50),
    discount_used BOOLEAN,
    amount INT
);

-- login_logs
CREATE TABLE login_logs (
    log_id INT PRIMARY KEY,
    user_id INT,
    login_date DATE,
    device VARCHAR(50),
    ip VARCHAR(50)
);


